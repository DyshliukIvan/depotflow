CREATE table products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(64) UNIQUE NOT NULL,
    name varchar(255) not null,
    created_at TIMESTAMPTZ not null default current_timestamp
);

CREATE table warehouses (
    id BIGINT GENERATED bY default AS IDENTITY primary key,
    code varchar(64) unique not null,
    name varchar(255) not null,
    created_at TIMESTAMPTZ not null default current_timestamp
);

CREATE table stock_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    warehouse_id BIGINT NOT NULL REFERENCES warehouses(id),
    on_hand INTEGER NOT NULL DEFAULT 0,
    reserved INTEGER NOT NULL DEFAULT 0,
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_stock_items_product_warehouse UNIQUE (product_id, warehouse_id),
    CONSTRAINT ck_stock_items_quantities CHECK (on_hand >= 0 AND reserved >= 0 AND reserved <= on_hand)

);

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_item_id BIGINT NOT NULL REFERENCES stock_items(id),
    type VARCHAR(32) NOT NULL,
    quantity integer NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_stock_movements_quantity CHECK (quantity > 0),
    CONSTRAINT ck_stock_movements_type CHECK (type IN ('RECEIVE', 'RESERVE', 'RELEASE', 'SHIP'))
);

CREATE INDEX idx_stock_movements_item_time
    ON stock_movements (stock_item_id, occurred_at DESC);